"""Nonlinear measurement experiment — synthetic validation.

Tests DECAT robustness when observations are generated by nonlinear functions
of the latent variables

Three new conditions are run (Condition 1 = existing main experiment data):

  Condition 2 — nonlinear_obs:   entire linear mixture → MLP → observations
  Condition 3 — nonlinear_batch: biology linear, batch → MLP → observations
  Condition 4 — nonlinear_both:  both biology and batch enter nonlinearly

All conditions use baseline regime, 50 seeds, pure scenarios, N_eval=1000.

Run counts
----------
  3 conditions × 50 seeds × 7 models = 1,050 model trainings.

Usage
-----
    # Full run (train then eval):
    python3 experiments/synthetic/run_nonlinear_experiment.py

    # Train only:
    python3 experiments/synthetic/run_nonlinear_experiment.py --phase train

    # Eval only (representations already trained):
    python3 experiments/synthetic/run_nonlinear_experiment.py --phase eval

    # Smoke test (2 seeds per condition):
    python3 experiments/synthetic/run_nonlinear_experiment.py --n-runs-override 2
"""
from __future__ import annotations

import argparse
import os
import time
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from pipeline.evaluate_scenarios import (
    AlphaConfig, EvalConfig, evaluate_runs_parallel, make_alpha_configs,
)
from pipeline.train_models import ModelConfig, is_run_trained, train_runs_gpu_pool
from simulator.simulator import SimulatorConfig

# Constants — match main experiment exactly
K          = 50
N_TRAIN    = 1500
N_EVAL     = 1000
D_OBS      = 1024
BSM        = 2.0
N_SEEDS    = 50
SEED       = 42
SEED_STRIDE = 37

OUTPUT_BASE = Path(os.environ.get(
    "DECAT_NONLINEAR_DIR",
    "./data/nonlinear_experiment",
))
REPR_DIR    = OUTPUT_BASE / "repr"
RESULTS_DIR = OUTPUT_BASE / "results"

# Conditions to run (Condition 1 reuses existing main experiment data)
CONDITIONS = [
    "nonlinear_batch",  # Condition 3 — primary: addresses AC's nonlinear confounding
    "nonlinear_obs",    # Condition 2 — general nonlinear embeddings
    "nonlinear_both",   # Condition 4 — fully nonlinear (optional)
]

BASELINE_REGIME = {"beta_s": 1.0, "beta_h": 1.0, "beta_r": 1.0, "beta_b": 0.75}


def _model_configs(k: int = K) -> list[ModelConfig]:
    return [
        ModelConfig("cca",  f"cca_K{k}", {"n_components": k}, False),
        ModelConfig("clip", f"clip_K{k}", {
            "latent_dim": k, "hidden_multiplier": 4, "temperature": 0.07,
            "lr": 1e-3, "n_epochs": 200, "batch_size": 1024,
        }, False),
        ModelConfig("jive", f"jive_K{k}", {"n_components": k, "n_individual": k}, True),
        ModelConfig("dssl", f"dssl_l0.01_b0.01_K{k}", {
            "latent_dim": k, "hidden_multiplier": 4, "beta": 0.01, "lambda_orth": 0.01,
            "temperature": 0.07, "aug_noise_std": 0.1, "lr": 1e-3,
            "n_epochs_shared": 125, "n_epochs_specific": 50, "batch_size": 1024,
        }, True),
        ModelConfig("dssl", f"dssl_l0.1_b0.1_K{k}", {
            "latent_dim": k, "hidden_multiplier": 4, "beta": 0.1, "lambda_orth": 0.1,
            "temperature": 0.07, "aug_noise_std": 0.1, "lr": 1e-3,
            "n_epochs_shared": 125, "n_epochs_specific": 50, "batch_size": 1024,
        }, True),
        ModelConfig("dssl", f"dssl_l1.0_b1.0_K{k}", {
            "latent_dim": k, "hidden_multiplier": 4, "beta": 1.0, "lambda_orth": 1.0,
            "temperature": 0.07, "aug_noise_std": 0.1, "lr": 1e-3,
            "n_epochs_shared": 75, "n_epochs_specific": 50, "batch_size": 1024,
        }, True),
        ModelConfig("dssl", f"dssl_l10.0_b10.0_K{k}", {
            "latent_dim": k, "hidden_multiplier": 4, "beta": 10.0, "lambda_orth": 10.0,
            "temperature": 0.07, "aug_noise_std": 0.1, "lr": 1e-3,
            "n_epochs_shared": 75, "n_epochs_specific": 50, "batch_size": 1024,
        }, True),
    ]


def _make_cfg(seed: int, condition: str) -> SimulatorConfig:
    """Build a SimulatorConfig for one nonlinear run."""
    return SimulatorConfig(
        latent_dim=K, d_h=D_OBS, d_r=D_OBS,
        n_a=N_TRAIN, n_a_prime=N_EVAL, n_b=N_EVAL, n_c=N_EVAL,
        alpha_s=0.0, alpha_h=0.0, alpha_r=0.0, alpha_b=0.0,
        batch_align=1.0,
        batch_shift_magnitude=BSM,
        measurement_variant=condition,
        seed=seed,
        **BASELINE_REGIME,
    )


def build_run_configs(
    conditions: list[str] | None = None,
    n_runs_override: int | None = None,
) -> list[tuple[SimulatorConfig, str, str]]:
    """Return (cfg, run_id, condition) for all runs across conditions.

    Parameters
    ----------
    conditions : list[str] or None
        Subset of CONDITIONS to run (default: all).
    n_runs_override : int or None
        Cap seeds per condition (smoke test).

    Returns
    -------
    list of (SimulatorConfig, run_id, condition)
    """
    if conditions is None:
        conditions = CONDITIONS
    configs = []
    for condition in conditions:
        n_seeds = N_SEEDS if n_runs_override is None else min(N_SEEDS, n_runs_override)
        for i in range(n_seeds):
            seed = SEED + (len(configs) + i) * SEED_STRIDE
            run_id = f"{condition}_{i:03d}"
            cfg = _make_cfg(seed, condition)
            configs.append((cfg, run_id, condition))
    return configs


def _pure_alpha_configs() -> list[AlphaConfig]:
    """Pure-scenario alpha configs only (S1, S2B, S3, S4).

    Excludes mixed, transition, and proxy configs — we only need the four
    canonical scenarios for the nonlinear comparison.
    """
    all_cfgs = make_alpha_configs()
    pure_prefixes = ("s1_", "s2b_", "s3_", "s4h_", "s4r_")
    return [c for c in all_cfgs if c.config_id.startswith(pure_prefixes)]


def train_phase(
    run_configs: list[tuple[SimulatorConfig, str, str]],
    repr_dir: Path,
    batch_size: int = 8,
    n_gpus: int = 8,
    skip_existing: bool = True,
) -> None:
    """Train all 7 models for every run.

    Parameters
    ----------
    run_configs : list
    repr_dir : Path
    batch_size : int
    n_gpus : int
    skip_existing : bool
    """
    repr_dir.mkdir(parents=True, exist_ok=True)
    model_configs = _model_configs()

    pending = [
        (cfg, run_id) for cfg, run_id, _ in run_configs
        if not skip_existing or not is_run_trained(repr_dir / run_id, model_configs)
    ]
    n_skip = len(run_configs) - len(pending)
    print(f"\nTraining: {len(pending)} runs to train, {n_skip} skipped")
    if not pending:
        return

    t0 = time.time()
    n_total = len(pending)
    for batch_start in range(0, n_total, batch_size):
        batch = pending[batch_start:batch_start + batch_size]
        batch_num = batch_start // batch_size + 1
        n_batches = (n_total + batch_size - 1) // batch_size
        elapsed = time.time() - t0
        rate = batch_num / max(elapsed, 1)
        eta = (n_batches - batch_num) / rate if rate > 0 else float("inf")
        print(f"  batch {batch_num}/{n_batches}  "
              f"({elapsed:.0f}s elapsed, ETA {eta:.0f}s)", flush=True)
        train_runs_gpu_pool(batch, model_configs, repr_dir, n_gpus=n_gpus)

    print(f"Training complete in {time.time()-t0:.0f}s", flush=True)


def eval_phase(
    run_configs: list[tuple[SimulatorConfig, str, str]],
    repr_dir: Path,
    results_dir: Path,
    n_concurrent: int = 100,
    skip_existing: bool = True,
) -> None:
    """Evaluate all runs on pure alpha configs at N_eval=1000.

    Parameters
    ----------
    run_configs : list
    repr_dir : Path
    results_dir : Path
    n_concurrent : int
    skip_existing : bool
    """
    results_dir.mkdir(parents=True, exist_ok=True)
    alpha_cfgs = _pure_alpha_configs()
    eval_cfg = EvalConfig(
        n_eval_sizes=[N_EVAL],
        n_bootstrap=200,
        n_permutations=200,
        n_jobs=1,
    )
    run_ids = [run_id for _, run_id, _ in run_configs]
    print(f"\nEval: {len(run_ids)} runs × {len(alpha_cfgs)} alpha configs", flush=True)
    evaluate_runs_parallel(
        run_ids=run_ids,
        repr_dir=repr_dir,
        alpha_configs=alpha_cfgs,
        eval_config=eval_cfg,
        output_dir=results_dir,
        n_concurrent=n_concurrent,
    )


def main() -> None:
    """Parse CLI args and run the nonlinear experiment."""
    parser = argparse.ArgumentParser(description="DECAT nonlinear measurement experiment")
    parser.add_argument("--phase", choices=["train", "eval", "all"], default="all")
    parser.add_argument("--conditions", nargs="+", choices=CONDITIONS, default=None,
                        help="Subset of conditions to run (default: all three)")
    parser.add_argument("--n-runs-override", type=int, default=None,
                        help="Cap seeds per condition (smoke test)")
    parser.add_argument("--n-concurrent", type=int, default=100)
    parser.add_argument("--repr-dir",    type=str, default=str(REPR_DIR))
    parser.add_argument("--results-dir", type=str, default=str(RESULTS_DIR))
    parser.add_argument("--skip-existing", action="store_true", default=True)
    args = parser.parse_args()

    repr_dir    = Path(args.repr_dir)
    results_dir = Path(args.results_dir)
    conditions  = args.conditions or CONDITIONS

    run_configs = build_run_configs(conditions, args.n_runs_override)
    total_trainings = len(run_configs) * 7

    print("=" * 65)
    print("DECAT Nonlinear Measurement Experiment")
    print(f"  Conditions:      {conditions}")
    print(f"  Seeds/condition: {N_SEEDS if args.n_runs_override is None else args.n_runs_override}")
    print(f"  Total runs:      {len(run_configs)}")
    print(f"  Model trainings: {total_trainings}")
    print(f"  Phase:           {args.phase}")
    print(f"  repr_dir:        {repr_dir}")
    print(f"  results_dir:     {results_dir}")
    print("=" * 65, flush=True)

    t_start = time.time()

    if args.phase in ("train", "all"):
        train_phase(run_configs, repr_dir, skip_existing=args.skip_existing)

    if args.phase in ("eval", "all"):
        eval_phase(run_configs, repr_dir, results_dir,
                   n_concurrent=args.n_concurrent,
                   skip_existing=args.skip_existing)

    print(f"\nTotal elapsed: {(time.time()-t_start)/3600:.1f}h", flush=True)


if __name__ == "__main__":
    main()
